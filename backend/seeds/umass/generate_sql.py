#!/usr/bin/env python3
"""Turn artifacts.toml into a SQL seed, like seeds/examples.sql.

    python3 seeds/umass/generate_sql.py --mode dev  > umass-dev.sql
    python3 seeds/umass/generate_sql.py --mode prod > umass-prod.sql
    python3 seeds/umass/generate_sql.py --remove    > umass-remove.sql
    python3 seeds/umass/generate_sql.py --check     # validate only

Modes:
  dev   loads every artifact approved, so the app, search and Q&A see them
        at once. With --update, re-running replaces their text, tags, links
        and topic links with the file's current version.
  prod  loads every artifact as a draft, so each goes through Studio review
        before the app shows it. Never overwrites: an artifact already in the
        database (perhaps edited since in the Studio) is left alone.

Ids are fixed: each artifact's id is derived from its key in artifacts.toml
and starts with 5eed0081-, so the seed is safe to run more than once and
--remove can find exactly what it loaded. Changing a key makes a new artifact.

Standard library only (tomllib needs Python 3.11+).
"""

from __future__ import annotations

import argparse
import sys
import tomllib
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
PREFIX = "5eed0081"  # 5eed = seed, 0081 = issue #81
NAMESPACE = uuid.UUID("6f1b8c3e-2a7d-4e59-9b0c-8a1d2e3f4b5c")


def seed_id(*parts: str) -> str:
    u = str(uuid.uuid5(NAMESPACE, "/".join(parts)))
    return PREFIX + u[8:]


def q(value) -> str:
    """A SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


class Invalid(Exception):
    pass


def load(path: Path) -> list[dict]:
    data = tomllib.loads(path.read_text())
    arts = data.get("artifact", [])
    errors = []
    keys = {}
    for i, a in enumerate(arts):
        where = f"artifact #{i + 1} ({a.get('key', '?')})"
        for field in ("key", "name", "description"):
            if not str(a.get(field, "")).strip():
                errors.append(f"{where}: missing {field}")
        if a.get("key") in keys:
            errors.append(f"{where}: duplicate key")
        keys[a.get("key")] = a
        has_coords = "lat" in a or "lng" in a
        if has_coords and not ("lat" in a and "lng" in a):
            errors.append(f"{where}: needs both lat and lng")
        if has_coords and not (42.0 < a["lat"] < 43.0 and -73.0 < a["lng"] < -72.0):
            errors.append(f"{where}: coordinates are not near Amherst")
        if a.get("topic") and (has_coords or a.get("parent")):
            errors.append(f"{where}: a topic has no coordinates and no parent")
        if not a.get("topic") and not has_coords and not a.get("parent"):
            errors.append(f"{where}: needs coordinates or a parent to inherit them from")
        if not a.get("link"):
            errors.append(f"{where}: needs at least one source link")
        for link in a.get("link", []):
            if not str(link.get("url", "")).startswith(("https://", "http://")):
                errors.append(f"{where}: link url must start with http(s)://")
    for a in arts:
        p = a.get("parent")
        if p and p not in keys:
            errors.append(f"{a['key']}: parent {p!r} is not a key in the file")
        if p and keys.get(p, {}).get("topic"):
            errors.append(f"{a['key']}: parent {p!r} is a topic")
        for t in a.get("topics", []):
            if t.get("key") not in keys or not keys[t["key"]].get("topic"):
                errors.append(f"{a['key']}: topic {t.get('key')!r} is not a topic in the file")
    # Parents must not form a loop.
    for a in arts:
        seen, cur = set(), a
        while cur.get("parent"):
            if cur["key"] in seen:
                errors.append(f"{a['key']}: parent chain loops")
                break
            seen.add(cur["key"])
            cur = keys.get(cur["parent"], {})
    if errors:
        raise Invalid("\n".join(errors))
    return arts


def ordered(arts: list[dict]) -> list[dict]:
    """Topics first, then each parent before its children."""
    by_key = {a["key"]: a for a in arts}

    def depth(a):
        d = 0
        while a.get("parent"):
            a = by_key[a["parent"]]
            d += 1
        return d

    return sorted(arts, key=lambda a: (not a.get("topic"), depth(a)))


def generate(arts: list[dict], mode: str, update: bool) -> str:
    ids = {a["key"]: seed_id("artifact", a["key"]) for a in arts}
    out = [
        "-- Generated by seeds/umass/generate_sql.py from seeds/umass/artifacts.toml.",
        "-- Do not edit by hand: change artifacts.toml and regenerate.",
        f"-- Mode: {mode}{' --update' if update else ''}. {len(arts)} artifacts; ids start with {PREFIX}-.",
        "-- Descriptions are our own words; facts come from the sources linked on each artifact.",
        "",
        "BEGIN;",
        "",
    ]

    conflict = (
        "ON CONFLICT (id) DO UPDATE SET kind = EXCLUDED.kind, name = EXCLUDED.name, "
        "description = EXCLUDED.description, lat = EXCLUDED.lat, lng = EXCLUDED.lng, "
        "parent_id = EXCLUDED.parent_id, is_topic = EXCLUDED.is_topic"
        if update else "ON CONFLICT (id) DO NOTHING"
    )
    for a in ordered(arts):
        out.append(f"-- {a['name']}")
        out.append(
            "INSERT INTO artifacts (id, kind, name, description, lat, lng, parent_id, is_topic) VALUES ("
            f"{q(ids[a['key']])}, 'other', {q(a['name'])}, {q(a['description'].strip())}, "
            f"{q(a.get('lat'))}, {q(a.get('lng'))}, {q(ids.get(a.get('parent')) if a.get('parent') else None)}, "
            f"{q(bool(a.get('topic')))})\n{conflict};"
        )
    out.append("")

    if update:
        # Replace, not merge, so a tag or link removed from the file goes away too.
        id_list = ", ".join(q(ids[a["key"]]) for a in arts)
        out += [
            "-- --update: replace the seed's tags, links and topic links with the file's.",
            f"DELETE FROM artifact_tags WHERE artifact_id IN ({id_list});",
            f"DELETE FROM artifact_links WHERE artifact_id IN ({id_list});",
            f"DELETE FROM artifact_topics WHERE artifact_id IN ({id_list});",
            "",
        ]

    tag_rows = [(ids[a["key"]], t) for a in arts for t in a.get("tags", [])]
    if tag_rows:
        out.append("INSERT INTO artifact_tags (artifact_id, tag) VALUES")
        out.append(",\n".join(f"({q(i)}, {q(t)})" for i, t in tag_rows))
        out.append("ON CONFLICT DO NOTHING;")
        out.append("")

    link_rows = []
    for a in arts:
        for pos, link in enumerate(a.get("link", [])):
            link_rows.append((seed_id("link", a["key"], link["url"]), ids[a["key"]], link["url"], link.get("note", ""), pos))
    out.append("INSERT INTO artifact_links (id, artifact_id, url, note, position) VALUES")
    out.append(",\n".join(f"({q(lid)}, {q(aid)}, {q(url)}, {q(note)}, {pos})" for lid, aid, url, note, pos in link_rows))
    out.append("ON CONFLICT (id) DO NOTHING;")
    out.append("")

    topic_rows = [(ids[a["key"]], ids[t["key"]], t.get("note", "")) for a in arts for t in a.get("topics", [])]
    if topic_rows:
        out.append("INSERT INTO artifact_topics (artifact_id, topic_id, note) VALUES")
        out.append(",\n".join(f"({q(a)}, {q(t)}, {q(n)})" for a, t, n in topic_rows))
        out.append("ON CONFLICT DO NOTHING;")
        out.append("")

    if mode == "dev":
        out += [
            "-- dev: approve everything, so the app and search see it.",
            "UPDATE artifacts SET status = 'approved', reviewed_at = COALESCE(reviewed_at, now())",
            f"WHERE id::text LIKE '{PREFIX}-%' AND status <> 'approved';",
            "",
        ]
    else:
        out += ["-- prod: everything stays a draft until reviewed in the Studio.", ""]

    out.append("COMMIT;")
    return "\n".join(out) + "\n"


def remove_sql() -> str:
    return "\n".join([
        "-- Generated by seeds/umass/generate_sql.py --remove.",
        f"-- Deletes every artifact the UMass seed loaded (ids starting {PREFIX}-), with",
        "-- their tags, links and topic links. History rows stay.",
        "--",
        "-- Deleting an artifact also deletes everything under it (parent_id is",
        "-- ON DELETE CASCADE), so this refuses to run while any artifact an author",
        "-- created sits under a seed artifact. Move or delete those first.",
        "BEGIN;",
        "DO $$",
        "DECLARE n int;",
        "BEGIN",
        f"  SELECT count(*) INTO n FROM artifacts c JOIN artifacts p ON p.id = c.parent_id",
        f"  WHERE p.id::text LIKE '{PREFIX}-%' AND c.id::text NOT LIKE '{PREFIX}-%';",
        "  IF n > 0 THEN",
        "    RAISE EXCEPTION '% artifact(s) created by authors sit under seed artifacts; not removing', n;",
        "  END IF;",
        "END $$;",
        f"DELETE FROM artifacts WHERE id::text LIKE '{PREFIX}-%';",
        "COMMIT;",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--mode", choices=["dev", "prod"], default="prod")
    parser.add_argument("--update", action="store_true", help="dev only: overwrite what an earlier run loaded")
    parser.add_argument("--remove", action="store_true", help="print SQL that deletes everything this seed loads")
    parser.add_argument("--check", action="store_true", help="validate artifacts.toml and print a summary")
    parser.add_argument("--file", type=Path, default=HERE / "artifacts.toml")
    args = parser.parse_args()

    if args.remove:
        sys.stdout.write(remove_sql())
        return 0
    if args.update and args.mode != "dev":
        print("--update is for dev only: in production it would overwrite Studio edits", file=sys.stderr)
        return 2
    try:
        arts = load(args.file)
    except Invalid as err:
        print(f"{args.file.name} is not valid:\n{err}", file=sys.stderr)
        return 1
    if args.check:
        topics = sum(1 for a in arts if a.get("topic"))
        children = sum(1 for a in arts if a.get("parent"))
        print(f"{len(arts)} artifacts: {topics} topics, {children} inside a parent, "
              f"{len(arts) - topics - children} with their own location", file=sys.stderr)
        todo = [a["key"] for a in arts if a.get("check")]
        if todo:
            print(f"{len(todo)} carry a 'check' note for the fact checker", file=sys.stderr)
        return 0
    sys.stdout.write(generate(arts, args.mode, args.update))
    return 0


if __name__ == "__main__":
    sys.exit(main())
